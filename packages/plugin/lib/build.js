// Writes the pages.js file to cache dir
import fs from "fs"
import path from "path"
import glob from "fast-glob"
import { kebabCase } from "case-anything"
import { getImports } from "./get-imports.js"
import { outputFileIfChanged } from "./fs.js"

/**
 * @param {string} input
 * @returns string
 */
const slash = (input) => input.replace(/\\/g, "/")

/**
 *
 * @param {{pages:import('../index').Page[], pathParent: string, cacheDir: string, getPath: (slug: string) => string}} opts
 */
export const build = async (opts) => {
  console.log("building!")
  const pages = await Promise.all(
    opts.pages.map(async (page, index) => {
      const files = await glob(page.examples).then((files) =>
        Promise.all(
          files.sort().map(async (file) => {
            const contents = await fs.promises.readFile(file, "utf8")
            const imports = await getImports(contents, file)
            const title =
              file
                .split("/")
                .pop()
                // `[number]-` is used to to control order
                ?.replace(/^\d+\-/, "")
                ?.replace(/\.vue$/, "")
                ?.replace(/\.example$/, "") || ""
            // TODO: grab title/description/markdown content from example file content
            const slug = kebabCase(title)
            return {
              title,
              slug,
              path: file,
              absolutePath: path.resolve(file),
              contents,
              imports,
            }
          }),
        ),
      )
      if (files.length === 0) {
        console.warn(`No examples found for ${JSON.stringify(page)}`)
      }
      const contents = `
        <script setup>
        import { Playground } from "@viteplay/vue"
        
        // Can't use "style src" tag because of this issue https://github.com/vitejs/vite/pull/6233
        import "@viteplay/vue/dist/style.css"

        ${files
          .map((file, index) => {
            return `
            let modules_${index} = {}
            ${(file.imports || [])
              .map(
                (im, imIndex) => `import ${
                  im.imported === "default" ? "" : "* as "
                } module_${index}_${imIndex} from "${slash(
                  im.source[0] === "."
                    ? path.join(path.dirname(file.absolutePath), im.source)
                    : im.source,
                )}"
              modules_${index}["${im.source}"] = module_${index}_${imIndex}
              `,
              )
              .join("\n")}
            `
          })
          .join("\n")}
        </script>
        <template>
          <div>
            <h1>${page.title}</h1>
            ${files
              .map((file, index) => {
                return `
            <section>
            <h2 id="${file.slug}">${file.title}</h2>
            <Playground :modules="modules_${index}" :code="decodeURI(\`${encodeURI(
                  file.contents,
                )}\`)" />
            </section>
              `
              })
              .join("\n")}
          </div>
        </template>
        <style src="prismjs/themes/prism-tomorrow.css"></style>
      `

      const component = path.join(
        opts.cacheDir,
        `${index}-${kebabCase(page.title)}.vue`,
      )

      outputFileIfChanged(component, contents)

      const slug = kebabCase(page.title)

      return {
        title: page.title,
        path: opts.getPath(slug),
        component,
        children: files,
      }
    }),
  )

  const sideBarItems = pages
    .filter((p) => p.children.length > 0)
    .map((p) => ({
      text: p.title,
      link: p.path,
      headers: p.children.map((c) => ({
        title: c.title,
        slug: c.slug,
        level: 2,
      })),
    }))
  const layoutContents = `
<script setup>
import { RouteLayout } from "@viteplay/vue"

const items = ${JSON.stringify(sideBarItems)}
const pathParent = "${opts.pathParent}"
</script>

<template>
  <RouteLayout :items="items" :pathParent="pathParent" />
</template>
`

  const layoutComponent = path.join(opts.cacheDir, "AutoGeneratedLayout.vue")

  outputFileIfChanged(layoutComponent, layoutContents)

  const clientContent = `
    let pages = [
      {
        path: "${opts.pathParent}",
        component: () => import("${slash(layoutComponent)}"),
        children: [
          ${pages
            .map((page) => {
              return `{
              title: "${page.title}",
              path: "${page.path}",
              component: () => import("${slash(page.component)}")
            }`
            })
            .join(",\n")}
        ],
      },
    ]
    export { pages }
    `

  outputFileIfChanged(path.join(opts.cacheDir, "client.js"), clientContent)
}
